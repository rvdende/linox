//! Reads Linux evdev devices (/dev/input/event*) and turns their events
//! into the pointer and keyboard events the window manager handles.

use std::{
    fs::{self, File, OpenOptions},
    io::{self, Read},
    os::{
        fd::{AsFd, AsRawFd, BorrowedFd},
        unix::fs::OpenOptionsExt,
    },
    path::Path,
};

extern "C" {
    fn ioctl(fd: i32, request: u64, ...) -> i32;
}

const EV_SYN: u16 = 0;
const EV_KEY: u16 = 1;
const EV_REL: u16 = 2;
const EV_ABS: u16 = 3;
const REL_X: u16 = 0;
const REL_Y: u16 = 1;
const REL_WHEEL: u16 = 8;
const ABS_X: u16 = 0;
const ABS_Y: u16 = 1;
/// Key codes from BTN_MOUSE up are pointer buttons, not keys.
const BTN_MOUSE: u16 = 0x110;
const BTN_TOUCH: u16 = 0x14a;
const O_NONBLOCK: i32 = 0o4000;

#[derive(Clone, Copy, Debug, PartialEq)]
pub enum Event {
    Key {
        code: u32,
        pressed: bool,
    },
    Button {
        code: u32,
        pressed: bool,
    },
    /// Relative pointer motion in pixels.
    Motion {
        dx: f64,
        dy: f64,
    },
    /// Absolute pointer position as a fraction (0..=1) of the screen.
    Position {
        x: Option<f64>,
        y: Option<f64>,
    },
    /// Vertical scroll in wheel clicks, positive downwards.
    Scroll {
        clicks: f64,
    },
    /// End of one hardware report.
    Frame,
}

struct Device {
    file: File,
    ranges: [(i32, i32); 2],
}

pub struct Devices {
    devices: Vec<Device>,
}

impl Devices {
    /// Opens every readable event device under `directory`.
    pub fn open(directory: &Path) -> Self {
        let mut paths: Vec<_> = fs::read_dir(directory)
            .into_iter()
            .flatten()
            .flatten()
            .map(|entry| entry.path())
            .filter(|path| {
                path.file_name()
                    .and_then(|name| name.to_str())
                    .is_some_and(|name| name.starts_with("event"))
            })
            .collect();
        // Linox does not list /dev/input yet, so fall back to probing.
        if paths.is_empty() {
            paths = (0..8)
                .map(|index| directory.join(format!("event{index}")))
                .collect();
        }
        paths.sort();
        let devices = paths
            .iter()
            .filter_map(|path| {
                let file = OpenOptions::new()
                    .read(true)
                    .custom_flags(O_NONBLOCK)
                    .open(path)
                    .ok()?;
                let ranges = [absolute_range(&file, ABS_X), absolute_range(&file, ABS_Y)];
                eprintln!("linox-wm: input {}", path.display());
                Some(Device { file, ranges })
            })
            .collect();
        Self { devices }
    }

    pub fn fds(&self) -> impl Iterator<Item = BorrowedFd<'_>> {
        self.devices.iter().map(|device| device.file.as_fd())
    }

    /// Reads every pending event from every device.
    pub fn read(&mut self, mut sink: impl FnMut(Event)) {
        let mut buffer = [0_u8; 24 * 64];
        for device in &mut self.devices {
            loop {
                let length = match device.file.read(&mut buffer) {
                    Ok(0) => break,
                    Ok(length) => length,
                    Err(error) if error.kind() == io::ErrorKind::Interrupted => continue,
                    Err(_) => break,
                };
                for record in buffer[..length].as_chunks::<24>().0 {
                    if let Some(event) = decode(record, &device.ranges) {
                        sink(event);
                    }
                }
            }
        }
    }
}

/// Reads an absolute axis range with EVIOCGABS, defaulting to the
/// 0..=32767 range virtio tablets report.
fn absolute_range(file: &File, axis: u16) -> (i32, i32) {
    let mut info = [0_i32; 6];
    let request = 0x8018_4540 + u64::from(axis);
    // SAFETY: EVIOCGABS fills a struct input_absinfo of six i32 fields.
    let result = unsafe { ioctl(file.as_raw_fd(), request, info.as_mut_ptr()) };
    if result == 0 && info[2] > info[1] {
        (info[1], info[2])
    } else {
        (0, 32767)
    }
}

/// Decodes one struct input_event: a 16-byte timeval, then type, code and
/// value.
fn decode(record: &[u8], ranges: &[(i32, i32); 2]) -> Option<Event> {
    let kind = u16::from_ne_bytes(record[16..18].try_into().unwrap());
    let code = u16::from_ne_bytes(record[18..20].try_into().unwrap());
    let value = i32::from_ne_bytes(record[20..24].try_into().unwrap());
    let fraction = |axis: usize| {
        let (low, high) = ranges[axis];
        (f64::from(value - low) / f64::from(high - low)).clamp(0.0, 1.0)
    };
    match (kind, code) {
        (EV_SYN, 0) => Some(Event::Frame),
        // Repeats (value 2) are generated by clients from repeat_info.
        (EV_KEY, _) if value == 2 => None,
        (EV_KEY, BTN_TOUCH) => Some(Event::Button {
            code: u32::from(BTN_MOUSE),
            pressed: value != 0,
        }),
        (EV_KEY, code) if (BTN_MOUSE..BTN_MOUSE + 8).contains(&code) => Some(Event::Button {
            code: u32::from(code),
            pressed: value != 0,
        }),
        (EV_KEY, code) if code < BTN_MOUSE => Some(Event::Key {
            code: u32::from(code),
            pressed: value != 0,
        }),
        (EV_REL, REL_X) => Some(Event::Motion {
            dx: f64::from(value),
            dy: 0.0,
        }),
        (EV_REL, REL_Y) => Some(Event::Motion {
            dx: 0.0,
            dy: f64::from(value),
        }),
        (EV_REL, REL_WHEEL) => Some(Event::Scroll {
            clicks: -f64::from(value),
        }),
        (EV_ABS, ABS_X) => Some(Event::Position {
            x: Some(fraction(0)),
            y: None,
        }),
        (EV_ABS, ABS_Y) => Some(Event::Position {
            x: None,
            y: Some(fraction(1)),
        }),
        _ => None,
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn record(kind: u16, code: u16, value: i32) -> [u8; 24] {
        let mut bytes = [0; 24];
        bytes[16..18].copy_from_slice(&kind.to_ne_bytes());
        bytes[18..20].copy_from_slice(&code.to_ne_bytes());
        bytes[20..24].copy_from_slice(&value.to_ne_bytes());
        bytes
    }

    #[test]
    fn decodes_keys_buttons_and_axes() {
        let ranges = [(0, 32767), (0, 32767)];
        assert_eq!(
            decode(&record(EV_KEY, 30, 1), &ranges),
            Some(Event::Key {
                code: 30,
                pressed: true
            })
        );
        assert_eq!(decode(&record(EV_KEY, 30, 2), &ranges), None);
        assert_eq!(
            decode(&record(EV_KEY, 0x110, 0), &ranges),
            Some(Event::Button {
                code: 0x110,
                pressed: false
            })
        );
        assert_eq!(
            decode(&record(EV_ABS, ABS_Y, 32767), &ranges),
            Some(Event::Position {
                x: None,
                y: Some(1.0)
            })
        );
        assert_eq!(
            decode(&record(EV_REL, REL_WHEEL, 1), &ranges),
            Some(Event::Scroll { clicks: -1.0 })
        );
        assert_eq!(decode(&record(EV_SYN, 0, 0), &ranges), Some(Event::Frame));
    }
}
